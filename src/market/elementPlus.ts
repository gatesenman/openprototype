const rect = (
  name: string,
  x: number,
  y: number,
  width: number,
  height: number,
  fill: string,
  over: Partial<Node["style"]> = {},
): Node => ({
  id: id(),
  type: "rect",
  name,
  x,
  y,
  width,
  height,
  style: { fill: { type: "solid", color: fill }, radius: EP.radius, ...over },
});

const label = (
  content: string,
  x: number,
  y: number,
  width: number,
  color = EP.text,
  over: Partial<Node["text"]> = {},
): Node => ({
  id: id(),
  type: "text",
  name: content.slice(0, 10) || "文本",
  x,
  y,
  width,
  height: 20,
  style: {},
  text: {
    content,
    fontFamily: EP.font,
    fontSize: 14,
    fontWeight: 400,
    lineHeight: 1.4,
    color,
    align: "left",
    ...over,
  },
});

/** A solid-fill EP button as a single button node. */
function epButton(name: string, text: string, fill: string, fg = EP.white): Node {
  return {
    id: id("grp"),
    type: "button",
    name,
    x: 0,
    y: 0,
    width: 96,
    height: 40,
    style: { fill: { type: "solid", color: fill }, radius: EP.radius },
    text: {
      content: text,
      fontFamily: EP.font,
      fontSize: 14,
      fontWeight: 500,
      lineHeight: 1.4,
      color: fg,
      align: "center",
    },
  };
}

