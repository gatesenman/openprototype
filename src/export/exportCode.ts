import { DesignSystem, Frame, Node } from "@/schema/types";
import { nodeFill } from "@/render/resolve";

function styleObject(node: Node, ds: DesignSystem): Record<string, string | number> {
  const s = node.style;
  const css: Record<string, string | number> = {
    position: "absolute",
    left: node.x,
    top: node.y,
    width: node.width,
    height: node.height,
  };
  if (node.type !== "text" && node.type !== "line") css.background = nodeFill(node, ds);
  if (s.radius) css.borderRadius = s.radius;
  if (s.stroke) css.border = `${s.stroke.width}px solid ${s.stroke.color}`;
  if (s.opacity !== undefined) css.opacity = s.opacity;
  if (s.shadow) css.boxShadow = `${s.shadow.x}px ${s.shadow.y}px ${s.shadow.blur}px ${s.shadow.color}`;
  if (s.blur) css.filter = `blur(${s.blur}px)`;
  if (s.blendMode && s.blendMode !== "normal") css.mixBlendMode = s.blendMode;
  if (node.text) {
    css.display = "flex";
    css.alignItems = "center";
    css.justifyContent =
      node.type === "button" || node.text.align === "center"
        ? "center"
        : node.text.align === "right"
          ? "flex-end"
          : "flex-start";
    css.color = node.text.color;
    css.fontSize = node.text.fontSize;
    css.fontWeight = node.text.fontWeight;
    css.fontFamily = node.text.fontFamily;
  }
  return css;
}

const toCssText = (o: Record<string, string | number>): string =>
  Object.entries(o)
    .map(([k, v]) => {
      const prop = k.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
      const val = typeof v === "number" && !["opacity", "fontWeight", "zIndex"].includes(k) ? `${v}px` : v;
      return `${prop}:${val}`;
    })
    .join(";");

const toJsxStyle = (o: Record<string, string | number>): string =>
  "{{ " +
  Object.entries(o)
    .map(([k, v]) => `${k}: ${typeof v === "number" ? v : JSON.stringify(v)}`)
    .join(", ") +
  " }}";

function nodeJsx(node: Node, ds: DesignSystem, depth: number): string {
  const pad = "  ".repeat(depth);
  const style = toJsxStyle(styleObject(node, ds));
  const text = node.text ? node.text.content : "";
  const children = (node.children ?? []).map((c) => nodeJsx(c, ds, depth + 1)).join("\n");
  if (children) {
    return `${pad}<div style=${style}>\n${children}\n${pad}</div>`;
  }
  return `${pad}<div style=${style}>${text}</div>`;
}

/** Generate a self-contained React component for a frame. */
export function frameToReact(frame: Frame, ds: DesignSystem): string {
  const raw = (frame.name || "Screen").replace(/[^a-zA-Z0-9]/g, "") || "Screen";
  const comp = raw.charAt(0).toUpperCase() + raw.slice(1);
  const body = frame.nodes.map((n) => nodeJsx(n, ds, 2)).join("\n");
  return `export default function ${comp}() {
  return (
    <div style={{ position: "relative", width: ${frame.width}, height: ${frame.height}, background: "${frame.background}", overflow: "hidden" }}>
${body}
    </div>
  );
}
`;
}

function nodeHtml(node: Node, ds: DesignSystem, depth: number): string {
  const pad = "  ".repeat(depth);
  const style = toCssText(styleObject(node, ds));
  const text = node.text ? node.text.content : "";
  const children = (node.children ?? []).map((c) => nodeHtml(c, ds, depth + 1)).join("\n");
  if (children) return `${pad}<div style="${style}">\n${children}\n${pad}</div>`;
  return `${pad}<div style="${style}">${text}</div>`;
}

/** Generate plain HTML/CSS for a frame. */
export function frameToHtml(frame: Frame, ds: DesignSystem): string {
  const body = frame.nodes.map((n) => nodeHtml(n, ds, 3)).join("\n");
  return `<!doctype html>
<html lang="zh-CN">
<head><meta charset="utf-8"/><title>${frame.name}</title></head>
<body style="margin:0">
  <div style="position:relative;width:${frame.width}px;height:${frame.height}px;background:${frame.background};overflow:hidden">
${body}
  </div>
</body>
</html>
`;
}

/* ------------------------------------------------------------------ *
 *  CSS export (class-based rules)                                      *
 * ------------------------------------------------------------------ */

const cssClass = (node: Node, i: number): string => {
  const base = (node.name || node.type || "el").replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return `${base || "el"}-${i}`;
};

function nodeCssRules(node: Node, ds: DesignSystem, i: number, acc: string[]): void {
  const cls = cssClass(node, i);
  acc.push(`.${cls} {\n${toCssText(styleObject(node, ds)).split(";").map((d) => "  " + d + ";").join("\n")}\n}`);
  (node.children ?? []).forEach((c, j) => nodeCssRules(c, ds, i * 100 + j + 1, acc));
}

/** Generate a CSS stylesheet (one class per node) for a frame. */
export function frameToCss(frame: Frame, ds: DesignSystem): string {
  const acc: string[] = [];
  frame.nodes.forEach((n, i) => nodeCssRules(n, ds, i + 1, acc));
  return `/* ${frame.name || "Screen"} — generated by OpenPrototype */\n.frame {\n  position: relative;\n  width: ${frame.width}px;\n  height: ${frame.height}px;\n  background: ${frame.background};\n  overflow: hidden;\n}\n\n${acc.join("\n\n")}\n`;
}

/** CSS declaration block (no selector) for a single node — used by Dev Mode. */
export function nodeToCss(node: Node, ds: DesignSystem): string {
  return toCssText(styleObject(node, ds))
    .split(";")
    .filter(Boolean)
    .map((d) => d + ";")
    .join("\n");
}

/* ------------------------------------------------------------------ *
 *  Vue export (single-file component, inline styles)                   *
 * ------------------------------------------------------------------ */

function nodeVue(node: Node, ds: DesignSystem, depth: number): string {
  const pad = "  ".repeat(depth);
  const style = toCssText(styleObject(node, ds));
  const text = node.text ? node.text.content : "";
  const children = (node.children ?? []).map((c) => nodeVue(c, ds, depth + 1)).join("\n");
  if (children) return `${pad}<div style="${style}">\n${children}\n${pad}</div>`;
  return `${pad}<div style="${style}">${text}</div>`;
}

/** Generate a Vue 3 single-file component for a frame. */
export function frameToVue(frame: Frame, ds: DesignSystem): string {
  const body = frame.nodes.map((n) => nodeVue(n, ds, 3)).join("\n");
  return `<template>
  <div :style="root">
${body}
  </div>
</template>

<script setup lang="ts">
const root = {
  position: "relative",
  width: "${frame.width}px",
  height: "${frame.height}px",
  background: "${frame.background}",
  overflow: "hidden",
};
</script>
`;
}

/* ------------------------------------------------------------------ *
 *  Tailwind export (arbitrary-value utility classes)                   *
 * ------------------------------------------------------------------ */

function tailwindClasses(node: Node, ds: DesignSystem): string {
  const s = node.style;
  const c: string[] = ["absolute", `left-[${node.x}px]`, `top-[${node.y}px]`, `w-[${node.width}px]`, `h-[${node.height}px]`];
  if (node.type !== "text" && node.type !== "line") c.push(`bg-[${nodeFill(node, ds)}]`);
  if (s.radius) c.push(`rounded-[${s.radius}px]`);
  if (s.stroke) c.push(`border-[${s.stroke.width}px]`, `border-[${s.stroke.color}]`);
  if (s.opacity !== undefined) c.push(`opacity-[${s.opacity}]`);
  if (s.blur) c.push(`blur-[${s.blur}px]`);
  if (s.blendMode && s.blendMode !== "normal") c.push(`mix-blend-${s.blendMode}`);
  if (node.text) {
    c.push("flex", "items-center");
    c.push(node.type === "button" || node.text.align === "center" ? "justify-center" : node.text.align === "right" ? "justify-end" : "justify-start");
    c.push(`text-[${node.text.color}]`, `text-[${node.text.fontSize}px]`, `font-[${node.text.fontWeight}]`);
  }
  return c.join(" ");
}

function nodeTailwind(node: Node, ds: DesignSystem, depth: number): string {
  const pad = "  ".repeat(depth);
  const cls = tailwindClasses(node, ds);
  const text = node.text ? node.text.content : "";
  const children = (node.children ?? []).map((c) => nodeTailwind(c, ds, depth + 1)).join("\n");
  if (children) return `${pad}<div className="${cls}">\n${children}\n${pad}</div>`;
  return `${pad}<div className="${cls}">${text}</div>`;
}

/** Tailwind class string for a single node — used by Dev Mode. */
export function nodeToTailwind(node: Node, ds: DesignSystem): string {
  return tailwindClasses(node, ds);
}

/** Generate a Tailwind-based React component for a frame. */
export function frameToTailwind(frame: Frame, ds: DesignSystem): string {
  const raw = (frame.name || "Screen").replace(/[^a-zA-Z0-9]/g, "") || "Screen";
  const comp = raw.charAt(0).toUpperCase() + raw.slice(1);
  const body = frame.nodes.map((n) => nodeTailwind(n, ds, 2)).join("\n");
  return `export default function ${comp}() {
  return (
    <div className="relative overflow-hidden" style={{ width: ${frame.width}, height: ${frame.height}, background: "${frame.background}" }}>
${body}
    </div>
  );
}
`;
}

