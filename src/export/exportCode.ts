export type CodeLang = "css" | "html" | "react" | "vue" | "tailwind";

export const CODE_LANGS: { id: CodeLang; label: string; ext: string; mime: string }[] = [
  { id: "css", label: "CSS", ext: "css", mime: "text/css" },
  { id: "html", label: "HTML", ext: "html", mime: "text/html" },
  { id: "react", label: "React", ext: "tsx", mime: "text/plain" },
  { id: "vue", label: "Vue", ext: "vue", mime: "text/plain" },
  { id: "tailwind", label: "Tailwind", ext: "tsx", mime: "text/plain" },
];

/** Generate code for an entire frame in the requested language. */
export function frameToCode(frame: Frame, ds: DesignSystem, lang: CodeLang): string {
  switch (lang) {
    case "css":
      return frameToCss(frame, ds);
    case "html":
      return frameToHtml(frame, ds);
    case "vue":
      return frameToVue(frame, ds);
    case "tailwind":
      return frameToTailwind(frame, ds);
    case "react":
    default:
      return frameToReact(frame, ds);
  }
}

/** Generate a focused code snippet for a single node — powers Dev Mode. */
export function nodeToCode(node: Node, ds: DesignSystem, lang: CodeLang): string {
  switch (lang) {
    case "css":
      return `.${cssClass(node, 1)} {\n${nodeToCss(node, ds).split("\n").map((l) => "  " + l).join("\n")}\n}`;
    case "tailwind":
      return `<div className="${nodeToTailwind(node, ds)}">${node.text?.content ?? ""}</div>`;
    case "html":
      return nodeHtml(node, ds, 0);
    case "vue":
      return nodeVue(node, ds, 0);
    case "react":
    default:
      return nodeJsx(node, ds, 0);
  }
}

export function download(content: string, filename: string, mime = "text/plain"): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
