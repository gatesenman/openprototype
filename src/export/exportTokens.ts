import { DesignSystem } from "@/schema/types";

/** Export design tokens as CSS custom properties. */
export function tokensToCss(ds: DesignSystem): string {
  const c = Object.entries(ds.tokens.colors)
    .map(([k, v]) => `  --color-${k}: ${v};`)
    .join("\n");
  const r = Object.entries(ds.tokens.radii)
    .map(([k, v]) => `  --radius-${k}: ${v}px;`)
    .join("\n");
  const s = Object.entries(ds.tokens.spacing)
    .map(([k, v]) => `  --space-${k}: ${v}px;`)
    .join("\n");
  const f = Object.entries(ds.tokens.fonts.sizes)
    .map(([k, v]) => `  --font-${k}: ${v}px;`)
    .join("\n");
  return `:root {\n  /* ${ds.name} — generated by OpenPrototype */\n  --font-family: ${ds.tokens.fonts.family};\n${c}\n${r}\n${s}\n${f}\n}\n`;
}

/** Export design tokens as a JSON object (W3C-ish token shape). */
export function tokensToJson(ds: DesignSystem): string {
  return JSON.stringify(
    {
      name: ds.name,
      color: ds.tokens.colors,
      radius: ds.tokens.radii,
      spacing: ds.tokens.spacing,
      font: { family: ds.tokens.fonts.family, size: ds.tokens.fonts.sizes },
    },
    null,
    2,
  );
}
